import "strings"

// Help system and command registry catalog:
//   - helptext_<page>_{title,desc,usage,example,extra}: help pages (MarkdownV2,
//     except title which is plain text escaped by the renderer). Examples that
//     are pure command syntax stay in code and have no key.
//   - helptext_btn_<command>, helptext_cat_<category>: help buttons and headings.
//   - cmd_<command>: command descriptions for /help and Telegram's command menu
//     (plain text).
//   - menu_*: routing-level replies (unsupported callback actions).

// CommandKey returns the catalog key holding the description of command name:
// "cmd_" followed by name with every character outside [a-z0-9] replaced by "_".
func CommandKey(name string) string {
	var sb strings.Builder
	sb.WriteString("cmd_")
	for _, r := range strings.ToLower(name) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			sb.WriteRune(r)
		} else {
			sb.WriteByte('_')
		}
	}
	return sb.String()
}

